import { randomBytes, randomUUID } from 'node:crypto'
import { chmod, readFile, rename, writeFile } from 'node:fs/promises'
import path from 'node:path'

const DEFAULT_OAUTH_ITEM = 'op://Private/Tengri GitHub OAuth'
const DEFAULT_ENV_PATH = path.resolve(import.meta.dir, '..', '.env.local')

type EnvironmentUpdates = Record<string, string>

export function mergeEnvironment(source: string, updates: EnvironmentUpdates): string {
  const lines = source ? source.replace(/\r\n/g, '\n').split('\n') : []
  const remaining = new Map(Object.entries(updates))
  const merged = lines.map((line) => {
    const match = /^([A-Z][A-Z0-9_]*)=/.exec(line)
    if (!match) return line

    const key = match[1]
    const value = remaining.get(key)
    if (value === undefined) return line

    remaining.delete(key)
    return `${key}=${encodeEnvironmentValue(value)}`
  })

  while (merged.at(-1) === '') merged.pop()
  if (remaining.size > 0) {
    if (merged.length > 0) merged.push('')
    merged.push('# Local Tengri BFF. Generated by `bun run setup:tengri-local`.')
    for (const [key, value] of remaining) merged.push(`${key}=${encodeEnvironmentValue(value)}`)
  }

  return `${merged.join('\n')}\n`
}

export function readEnvironmentValue(source: string, key: string): string {
  const line = source
    .replace(/\r\n/g, '\n')
    .split('\n')
    .find((candidate) => candidate.startsWith(`${key}=`))
  if (!line) return ''

  const value = line.slice(key.length + 1).trim()
  if (!value.startsWith('"')) return value

  try {
    const parsed: unknown = JSON.parse(value)
    return typeof parsed === 'string' ? parsed : ''
  } catch {
    return ''
  }
}

export function retainOrGenerateSecret(existing: string, generate = () => randomBytes(48).toString('base64url')) {
  return existing.length >= 32 ? existing : generate()
}

async function main() {
  const envPath = resolveEnvironmentPath(process.argv.slice(2))
  const existing = await readOptionalFile(envPath)
  const oauthItem = process.env.TENGRI_GITHUB_OAUTH_OP_ITEM?.trim() || DEFAULT_OAUTH_ITEM

  const githubClientId = await readCredential('GITHUB_CLIENT_ID', `${oauthItem}/username`)
  const githubClientSecret = await readCredential('GITHUB_CLIENT_SECRET', `${oauthItem}/password`)
  if (!githubClientId || !githubClientSecret) throw new Error('GitHub OAuth credentials must not be empty')

  const updates: EnvironmentUpdates = {
    BETTER_AUTH_URL:
      process.env.BETTER_AUTH_URL?.trim() ||
      readEnvironmentValue(existing, 'BETTER_AUTH_URL') ||
      'http://127.0.0.1:3000',
    BETTER_AUTH_SECRET: retainOrGenerateSecret(readEnvironmentValue(existing, 'BETTER_AUTH_SECRET')),
    GITHUB_CLIENT_ID: githubClientId,
    GITHUB_CLIENT_SECRET: githubClientSecret,
    TENGRI_GRPC_ENDPOINT:
      process.env.TENGRI_GRPC_ENDPOINT?.trim() ||
      readEnvironmentValue(existing, 'TENGRI_GRPC_ENDPOINT') ||
      '127.0.0.1:50051',
    TENGRI_GRPC_TLS:
      process.env.TENGRI_GRPC_TLS?.trim() || readEnvironmentValue(existing, 'TENGRI_GRPC_TLS') || 'false',
    TENGRI_INTERNAL_HMAC_SECRET: retainOrGenerateSecret(readEnvironmentValue(existing, 'TENGRI_INTERNAL_HMAC_SECRET')),
    TENGRI_PUBLIC_URL:
      process.env.TENGRI_PUBLIC_URL?.trim() ||
      readEnvironmentValue(existing, 'TENGRI_PUBLIC_URL') ||
      'http://localhost:8080',
  }

  const output = mergeEnvironment(existing, updates)
  const temporaryPath = `${envPath}.${process.pid}.${randomUUID()}.tmp`
  await writeFile(temporaryPath, output, { encoding: 'utf8', flag: 'wx', mode: 0o600 })
  await rename(temporaryPath, envPath)
  await chmod(envPath, 0o600)

  console.log(`Configured ${path.relative(process.cwd(), envPath) || envPath} with mode 0600.`)
  console.log('Loaded the GitHub OAuth client from 1Password and preserved existing local Tengri signing keys.')
}

function resolveEnvironmentPath(args: string[]) {
  const envIndex = args.indexOf('--env-file')
  if (envIndex === -1) return DEFAULT_ENV_PATH
  const value = args[envIndex + 1]?.trim()
  if (!value) throw new Error('--env-file requires a path')
  return path.resolve(value)
}

async function readOptionalFile(filePath: string) {
  try {
    return await readFile(filePath, 'utf8')
  } catch (error) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') return ''
    throw error
  }
}

async function readCredential(environmentName: 'GITHUB_CLIENT_ID' | 'GITHUB_CLIENT_SECRET', reference: string) {
  const configured = process.env[environmentName]?.trim()
  if (configured) return configured

  const executable = Bun.which('op')
  if (!executable) throw new Error('1Password CLI is required; install `op` or set the GitHub OAuth environment values')

  const args = ['read', reference]
  const account = process.env.OP_ACCOUNT?.trim()
  if (account) args.push('--account', account)
  const child = Bun.spawn([executable, ...args], {
    env: process.env,
    stdin: 'ignore',
    stdout: 'pipe',
    stderr: 'pipe',
  })
  const [exitCode, stdout] = await Promise.all([child.exited, new Response(child.stdout).text()])
  if (exitCode !== 0) {
    throw new Error(
      `Unable to read ${environmentName} from 1Password. Run \`eval "$(op signin --account <account>)"\` first.`,
    )
  }
  return stdout.trim()
}

function encodeEnvironmentValue(value: string) {
  return /^[A-Za-z0-9_./:@+-]+$/.test(value) ? value : JSON.stringify(value)
}

if (import.meta.main) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : String(error))
    process.exitCode = 1
  })
}
