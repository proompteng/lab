          'BROKER_OBSERVATION_UNAVAILABLE','BROKER_ACCOUNT_UNAVAILABLE','BROKER_POSITIONS_CHANGED',
          'BROKER_ORDERS_CHANGED','BROKER_CASH_CHANGED','AUTHORITY_GENERATION_CHANGED','STRATEGY_BINDING_CHANGED',
          'MUTATION_AUTHORIZATION_FAILED','WRITER_FENCE_FAILED','INSTRUMENT_NOT_ELIGIBLE','CAPITAL_GRANT_MISSING',
          'CAPITAL_GRANT_CHANGED','CAPITAL_AUTHORITY_CHANGED','RISK_POLICY_INVALID','RISK_POLICY_CHANGED',
