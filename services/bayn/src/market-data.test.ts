describe('finalized Signal snapshot reader', () => {
  test('preserves ClickHouse retryability for check, inspect, and load failures', () => {
    for (const operation of ['check', 'inspect', 'inspect-publication', 'load'] as const) {
      const authorization = marketDataOperationError(
        operation,
        'Signal query failed',
        SqlError.make({
          reason: AuthorizationError.make({ cause: new Error('SELECT denied'), operation: 'query' }),
        }),
      )
      const connection = marketDataOperationError(
        operation,
        'Signal query failed',
        SqlError.make({
          reason: ConnectionError.make({ cause: new Error('connection reset'), operation: 'query' }),
        }),
      )

      expect(authorization).toMatchObject({ component: 'market-data', operation, retryable: false })
      expect(connection).toMatchObject({ component: 'market-data', operation, retryable: true })
    }

    expect(marketDataOperationError('load', 'Signal query failed', { _tag: 'UnrelatedTaggedFailure' })).toMatchObject({
      component: 'market-data',
      operation: 'load',
      retryable: true,
    })
  })

  test('reproduces the publisher contract before exposing bounded numeric bars', () => {
    const fixture = makeFixture()
    const snapshot = verificationSuccess(verifyFinalizedSnapshot(fixture.rows, fixture.request))
    const source = fixture.rows.manifests[0]

    expect(snapshot.bars).toHaveLength(4)
    expect(snapshot.manifest).toMatchObject({
      schemaVersion: 'bayn.input-manifest.v3',
      rowCount: 4,
      sessionCount: 2,
      firstSession: '2025-01-02',
      lastSession: '2025-01-03',
      finalizedSnapshot: {
        snapshotId: source.snapshot_id,
        publicationId: source.manifest_content_hash,
        contentHash: source.bars_content_hash,
        sessionsContentHash: source.sessions_content_hash,
        sourceFeed: DataFeed.Sip,
        universeId: 'cross-asset-taa-v1',
        universeSymbolHash,
        symbols,
      },
    })
    expect(snapshot.manifest.hash).toMatch(/^[a-f0-9]{64}$/)
    expect(snapshot.bars.every((bar) => bar.open > 0 && bar.close > 0)).toBe(true)
  })

  test('checks the finalized publication identity without loading sessions or bars', () => {
    const fixture = makeFixture()
    const publication = verificationSuccess(verifyManifest(fixture.rows.manifests, fixture.request)).finalizedSnapshot

    expect(publication).toMatchObject({
      snapshotId,
      publicationId: fixture.rows.manifests[0].manifest_content_hash,
      calendarVersion: fixture.request.calendarVersion,
      asOfSession: fixture.request.publicationAsOf,
      symbols,
      rowCount: 4,
      sessionCount: 2,
    })
    expect(verificationFailure(verifyManifest([], fixture.request))).toMatchObject({
      _tag: 'ManifestCountMismatch',
      snapshotId,
      count: 0,
    })
  })

  test('precommits the exact input manifest from manifest and calendar rows without bars', () => {
    const fixture = makeFixture()
    const inspection = verificationSuccess(
      verifyCalendar(fixture.rows.sessions, fixture.rows.manifests, fixture.request),
    )
    const snapshot = verificationSuccess(verifyFinalizedSnapshot(fixture.rows, fixture.request))

    expect(inspection.inputManifest).toEqual(snapshot.manifest)
    expect(inspection.boundedSessions.map((session) => session.session_date)).toEqual(['2025-01-02', '2025-01-03'])
    expect(inspection.boundedSessions.at(-1)).toMatchObject({
      calendar_version: 'alpaca-us-equity-calendar-v1',
      session_date: '2025-01-03',
      close_time: '16:00',
      timezone: 'America/New_York',
    })
  })

  test('rejects duplicate manifests, sessions, and bars', () => {
    const fixture = makeFixture()
    expect(
      verificationFailure(
        verifyFinalizedSnapshot(
          { ...fixture.rows, manifests: [...fixture.rows.manifests, fixture.rows.manifests[0]] },
          fixture.request,
        ),
      ),
    ).toMatchObject({ _tag: 'ManifestCountMismatch', count: 2 })
    expect(
      verificationFailure(
        verifyFinalizedSnapshot(
          { ...fixture.rows, sessions: [...fixture.rows.sessions, fixture.rows.sessions[0]] },
          fixture.request,
        ),
      ),
    ).toMatchObject({ _tag: 'DuplicateSession', sessionDate: '2025-01-02' })
    expect(
      verificationFailure(
        verifyFinalizedSnapshot(
          { ...fixture.rows, bars: [...fixture.rows.bars, fixture.rows.bars[0]] },
          fixture.request,
        ),
      ),
    ).toMatchObject({ _tag: 'DuplicateBar', symbol: 'EEM', sessionDate: '2025-01-02' })
  })

  test('normalizes row ordering and classifies hostile, missing, duplicate, and degenerate pure inputs', () => {
    const fixture = makeFixture()
    const expected = verificationSuccess(verifyFinalizedSnapshot(fixture.rows, fixture.request))
    const reorderings: readonly SnapshotRows[] = [
      { ...fixture.rows, bars: [...fixture.rows.bars].reverse() },
      { ...fixture.rows, sessions: [...fixture.rows.sessions].reverse() },
      {
        ...fixture.rows,
        bars: [fixture.rows.bars[2], fixture.rows.bars[0], fixture.rows.bars[3], fixture.rows.bars[1]],
        sessions: [fixture.rows.sessions[1], fixture.rows.sessions[0]],
      },
    ]
    for (const rows of reorderings) {
      expect(verificationSuccess(verifyFinalizedSnapshot(rows, fixture.request))).toEqual(expected)
    }

    const hostileDecode = decodeSnapshotRows([{ ...fixture.rows.bars[0], adjusted_close: Number.NaN }], [], [])
    expect(verificationFailure(hostileDecode)).toMatchObject({ _tag: 'RowDecodeFailed', rows: 'bars' })

    const cases = [
      {
        rows: { ...fixture.rows, bars: [...fixture.rows.bars, fixture.rows.bars[0]] },
        expected: { _tag: 'DuplicateBar', symbol: 'EEM', sessionDate: '2025-01-02' },
      },
      {
        rows: { ...fixture.rows, sessions: fixture.rows.sessions.slice(1) },
        expected: { _tag: 'SessionFieldMismatch', field: 'count' },
      },
    ] as const
    for (const { expected: failure, rows } of cases) {
      expect(verificationFailure(verifyFinalizedSnapshot(rows, fixture.request))).toMatchObject(failure)
    }

    const degenerateBars = [{ ...fixture.rows.bars[0], adjusted_close: 'NaN' }, ...fixture.rows.bars.slice(1)]
    const barsContentHash = Result.getOrThrow(
      canonicalHashV1Result(degenerateBars.map(({ snapshot_id: _, ...bar }) => bar)),
    )
    const sourceManifest = fixture.rows.manifests[0]
    const degenerateSnapshotId = Result.getOrThrow(
      canonicalHashV1Result({
        schemaVersion: sourceManifest.schema_version,
        provider: sourceManifest.provider,
        feed: sourceManifest.source_feed,
        adjustment: sourceManifest.adjustment,
        calendarVersion: sourceManifest.calendar_version,
        requestedStart: sourceManifest.requested_start,
        publicationAsOf: sourceManifest.publication_asof,
        symbols,
        barsContentHash,
        sessionsContentHash: sourceManifest.sessions_content_hash,
        universeId: sourceManifest.universe_id,
        universeSymbolHash: sourceManifest.universe_symbol_hash,
      }),
    )
    const { manifest_content_hash: _, ...sourceManifestMaterial } = sourceManifest
    const degenerateManifestMaterial = {
      ...sourceManifestMaterial,
      snapshot_id: degenerateSnapshotId,
      bars_content_hash: barsContentHash,
    }
    const degenerateRows: SnapshotRows = {
      bars: degenerateBars.map((bar) => ({ ...bar, snapshot_id: degenerateSnapshotId })),
      sessions: fixture.rows.sessions.map((session) => ({ ...session, snapshot_id: degenerateSnapshotId })),
      manifests: [
        {
          ...degenerateManifestMaterial,
          manifest_content_hash: Result.getOrThrow(canonicalHashV1Result(degenerateManifestMaterial)),
        },
      ],
    }
    expect(
      verificationFailure(
        verifyFinalizedSnapshot(degenerateRows, { ...fixture.request, snapshotId: degenerateSnapshotId }),
      ),
    ).toMatchObject({ _tag: 'DecimalInvalid', field: 'adjusted_close' })
  })

  test('rejects incomplete replica reads instead of silently shrinking history', () => {
    const fixture = makeFixture()
    expect(
      verificationFailure(verifyFinalizedSnapshot({ ...fixture.rows, manifests: [] }, fixture.request)),
    ).toMatchObject({ _tag: 'ManifestCountMismatch', count: 0 })
    expect(
      verificationFailure(
        verifyFinalizedSnapshot({ ...fixture.rows, sessions: fixture.rows.sessions.slice(1) }, fixture.request),
      ),
    ).toMatchObject({ _tag: 'SessionFieldMismatch', field: 'count' })
    expect(
      verificationFailure(
        verifyFinalizedSnapshot({ ...fixture.rows, bars: fixture.rows.bars.slice(1) }, fixture.request),
      ),
    ).toMatchObject({ _tag: 'BarFieldMismatch', field: 'barCount' })
  })

  test('rejects unexpected symbols and mixed publication provenance', () => {
    const fixture = makeFixture()
    const unexpected = [{ ...fixture.rows.bars[0], symbol: 'QQQ' }, ...fixture.rows.bars.slice(1)]
    expect(
      verificationFailure(verifyFinalizedSnapshot({ ...fixture.rows, bars: unexpected }, fixture.request)),
    ).toMatchObject({ _tag: 'BarFieldMismatch', field: 'universe' })

    const mixed = [{ ...fixture.rows.bars[0], source_feed: 'iex' as never }, ...fixture.rows.bars.slice(1)]
    expect(
      verificationFailure(verifyFinalizedSnapshot({ ...fixture.rows, bars: mixed }, fixture.request)),
    ).toMatchObject({ _tag: 'BarFieldMismatch', field: 'provenance' })
  })

  test('rejects a universe hash or evaluation history that differs from the compiled strategy', () => {
    const fixture = makeFixture()
    expect(
      verificationFailure(
        verifyFinalizedSnapshot(fixture.rows, { ...fixture.request, universeSymbolHash: '0'.repeat(64) }),
      ),
    ).toMatchObject({ _tag: 'ManifestFieldMismatch', field: 'universeSymbolHash' })
    expect(
      verificationFailure(
        verifyFinalizedSnapshot(fixture.rows, { ...fixture.request, historyStart: '2025-01-03' as const }),
      ),
    ).toMatchObject({ _tag: 'ManifestFieldMismatch', field: 'historyStart' })
  })

  test('rejects changed values, calendar contracts, counts, and hashes', () => {
    const fixture = makeFixture()
    const changed = [{ ...fixture.rows.bars[0], adjusted_close: '999.00000000' }, ...fixture.rows.bars.slice(1)]
    expect(
      verificationFailure(verifyFinalizedSnapshot({ ...fixture.rows, bars: changed }, fixture.request)),
    ).toMatchObject({ _tag: 'BarFieldMismatch', field: 'barsContentHash' })

    const wrongCalendar = [
      { ...fixture.rows.sessions[0], calendar_version: 'wrong-calendar' },
      ...fixture.rows.sessions.slice(1),
    ]
    expect(
      verificationFailure(verifyFinalizedSnapshot({ ...fixture.rows, sessions: wrongCalendar }, fixture.request)),
    ).toMatchObject({ _tag: 'SessionFieldMismatch', field: 'calendarVersion' })

    const badManifest = { ...fixture.rows.manifests[0], bar_count: 7 }
    expect(
      verificationFailure(verifyFinalizedSnapshot({ ...fixture.rows, manifests: [badManifest] }, fixture.request)),
    ).toMatchObject({ _tag: 'ManifestFieldMismatch', field: 'manifestContentHash' })
  })

  test('rejects future finalization, a different publication session, and non-session bounds', () => {
    const fixture = makeFixture()
    expect(
      verificationFailure(
        verifyFinalizedSnapshot(fixture.rows, {
          ...fixture.request,
          observedAt: '2025-01-04T00:59:59.999Z',
        }),
      ),
    ).toMatchObject({ _tag: 'SnapshotFinalizedInFuture' })
    expect(
      verificationFailure(verifyFinalizedSnapshot(fixture.rows, { ...fixture.request, publicationAsOf: '2025-01-02' })),
    ).toMatchObject({ _tag: 'ManifestFieldMismatch', field: 'publicationAsOf' })
    expect(
      verificationFailure(
        verifyFinalizedSnapshot(fixture.rows, {
          ...fixture.request,
          evaluationStart: '2025-01-04' as const,
          bounds: { ...fixture.request.bounds, evaluationStart: '2025-01-04' as const },
        }),
      ),
    ).toMatchObject({ _tag: 'BoundSessionMissing', field: 'evaluationStart' })
  })
})
